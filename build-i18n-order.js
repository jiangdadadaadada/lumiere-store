function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
}
const langs = Object.keys(T);
const orderBlocks = [];
const specBlocks = [];
langs.forEach(lang => {
  const o = T[lang], s = S[lang], mat = MATERIAL[lang];
  if (!o || o.length !== ORDER_KEYS.length) throw new Error(`order words mismatch: ${lang} (${o && o.length})`);
  if (!s || s.length !== SPEC_KEYS.length - 1) throw new Error(`spec words mismatch: ${lang} (${s && s.length})`);
  if (!mat) throw new Error(`material word missing: ${lang}`);
  orderBlocks.push(`window.I18N_ORDER.${lang} = {\n` +
    ORDER_KEYS.map((k, i) => `  '${k}':'${esc(o[i])}'`).join(',\n') + '\n};');
  specBlocks.push(`window.I18N_SPEC.${lang} = {\n` +
    SPEC_KEYS.map((k, i) => `  '${k}':'${esc(i < s.length ? s[i] : mat)}'`).join(',\n') + '\n};');
});

